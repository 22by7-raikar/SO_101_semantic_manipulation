"""Fit collision spheres to each SO-101 link mesh and write configs/so101_collision_spheres.yaml.

Needs the meshes (scripts/fetch_so101_meshes.py). Deterministic for a given --k, --margin-mm and
--seed. Radii include the margin and are rounded up to 0.1 mm, so every sampled surface point is
covered with at least ~0.9 mm to spare.
"""

import argparse
import hashlib
import math

import numpy as np
import yaml

from so101_semantic.collision import (
    SPHERES_PATH,
    bulge,
    fit_spheres,
    link_mesh,
    max_protrusion,
    surface_points,
)
from so101_semantic.kinematics import URDF_PATH, SO101Model


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--k", type=int, default=5, help="Spheres per link")
    parser.add_argument("--margin-mm", type=float, default=1.0)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    urdf = SO101Model().urdf
    links = {}
    for name in urdf.link_map:
        mesh = link_mesh(urdf, name, URDF_PATH.parent)
        if mesh is None:
            continue
        centres, radii = fit_spheres(surface_points(mesh, 30000, args.seed), args.k, args.seed)
        radii = np.array([math.ceil((r + args.margin_mm / 1000) * 1e4) / 1e4 for r in radii])
        centres = np.round(centres, 4)
        check = surface_points(mesh, 30000, args.seed + 1)
        gap_mm = max_protrusion(check, centres, radii) * 1000
        b = bulge(mesh, centres, radii) * 1000
        p95 = np.percentile(b, 95)
        print(f"{name:26s} max gap {gap_mm:+.2f} mm  bulge mean {b.mean():.1f} p95 {p95:.1f} mm")
        if gap_mm > 0:
            raise SystemExit(f"{name}: surface point outside spheres by {gap_mm:.2f} mm")
        links[name] = [
            {"center": [float(x) for x in c], "radius": float(r)}
            for c, r in zip(centres, radii, strict=True)
        ]

    header = (
        "# Generated by scripts/fit_collision_spheres.py; do not edit by hand.\n"
        "# Per link, in the link frame, metres. Radii include the margin.\n"
    )
    record = {
        "urdf": str(URDF_PATH.relative_to(SPHERES_PATH.parents[1])),
        "urdf_sha256": hashlib.sha256(URDF_PATH.read_bytes()).hexdigest(),
        "spheres_per_link": args.k,
        "margin_m": args.margin_mm / 1000,
        "seed": args.seed,
        "links": links,
    }
    SPHERES_PATH.write_text(
        header + yaml.safe_dump(record, sort_keys=False, default_flow_style=None)
    )
    print(f"Wrote {SPHERES_PATH}")


if __name__ == "__main__":
    main()
